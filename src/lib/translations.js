export const LanguageManager = {
  getCurrentLanguage() {
    return localStorage.getItem('farmdirect_lang') || 'en';
  },

  setLanguage(lang) {
    localStorage.setItem('farmdirect_lang', lang);
  },

  t(key) {
    const lang = LanguageManager.getCurrentLanguage();
    return TRANSLATIONS[lang]?.[key] || TRANSLATIONS['en'][key] || key;
  },

  // Returns formatted bilingual text "English / हिन्दी" or localized text
  bilingual(keyEn, keyHi) {
    const lang = LanguageManager.getCurrentLanguage();
    if (lang === 'hi') {
      return TRANSLATIONS['hi']?.[keyHi || keyEn] || TRANSLATIONS['en']?.[keyEn] || keyEn;
    }
    return TRANSLATIONS['en']?.[keyEn] || keyEn;
  }
};
